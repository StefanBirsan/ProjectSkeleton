    public static void DrawChar(GameRenderer gr, char ch, int px, int py, byte r, byte g, byte b, int scale)
    {
        if (!Glyphs.TryGetValue(ch, out var rows)) return;
        for (int row = 0; row < CharHeight; row++)
        {
            byte mask = rows[row];
            for (int col = 0; col < CharWidth; col++)
            {
                if ((mask & (1 << (CharWidth - 1 - col))) != 0)
                    gr.FillRect(px + col * scale, py + row * scale, scale, scale, r, g, b);
            }
        }
    }
